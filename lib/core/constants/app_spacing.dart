abstract class AppSpacing {
  /// Corner radius for cards and default buttons (16px)
  static const double cardRadius = 16.0;

  /// Corner radius for icon containers (12px)
  static const double iconRadius = 12.0;

  /// Icon container dimension (48x48px)
  static const double iconContainerSize = 48.0;

  /// Screen horizontal padding (24px)
  static const double horizontalPadding = 24.0;

  /// Major section vertical spacing (32px)
  static const double sectionSpacing = 32.0;

  /// Inter-element vertical spacing (16px)
  static const double elementSpacing = 16.0;

  /// Small element spacing (8px)
  static const double smallSpacing = 8.0;

  // Standard Spacing Aliases
  static const double spaceXS = 4.0;
  static const double spaceS = 8.0;
  static const double spaceM = 16.0;
  static const double spaceL = 24.0;
  static const double spaceXL = 32.0;

  // Standard Radius Aliases
  static const double radiusS = 8.0;
  static const double radiusM = 12.0;
  static const double radiusL = 16.0;
}
